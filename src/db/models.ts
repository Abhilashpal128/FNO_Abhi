export function createModels(connection: Connection): Record<Collection, Model<Record<string, unknown>>> {
  return Object.fromEntries(
    Object.entries(definitions).map(([name, fields]) => {
      const schema = new Schema(
        {
          id: { type: String, required: true, unique: true },
          ...fields,
          ...(expirable.has(name as Collection) ? { retentionAt: Date, retentionRetryAt: Date } : {}),
        },
        { collection: name, versionKey: false, strict: 'throw', minimize: false },
      );
      for (const [keys, options] of indexes[name as Collection] ?? []) schema.index(keys, options);
      if (expirable.has(name as Collection)) schema.index({ retentionAt: 1 }, { expireAfterSeconds: 0 });
      if (appendOnly.has(name as Collection)) {
        for (const method of [
          'updateOne',
          'updateMany',
          'findOneAndUpdate',
          'replaceOne',
          'deleteOne',
          'deleteMany',
          'findOneAndDelete',
        ] as const)
          schema.pre(method, function () {
            throw new Error(`${name} is append-only`);
          });
        schema.pre('save', function () {
          if (!this.isNew) throw new Error(`${name} is append-only`);
        });
      }
      return [name, connection.model<Record<string, unknown>>(name, schema)];
    }),
  ) as Record<Collection, Model<Record<string, unknown>>>;
}
